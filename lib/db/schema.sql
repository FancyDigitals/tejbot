-- TEJUROLEX GLOBAL RELATIONAL DATABASE SCHEMA

CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(36) PRIMARY KEY,
  email VARCHAR(255) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  name VARCHAR(255) NOT NULL,
  role VARCHAR(50) DEFAULT 'AGENT' CHECK (role IN ('OWNER', 'ADMIN', 'AGENT')),
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS customers (
  id VARCHAR(36) PRIMARY KEY,
  whatsapp_id VARCHAR(50) UNIQUE NOT NULL,
  phone VARCHAR(50) UNIQUE NOT NULL,
  name VARCHAR(255),
  email VARCHAR(255),
  avatar_url TEXT,
  notes TEXT,
  marketing_opt_out BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS leads (
  id VARCHAR(36) PRIMARY KEY,
  customer_id VARCHAR(36) UNIQUE NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  interested_course VARCHAR(255),
  current_level VARCHAR(50),
  learning_goal TEXT,
  preferred_schedule VARCHAR(100),
  location VARCHAR(255),
  lead_score INTEGER DEFAULT 0,
  lead_temperature VARCHAR(20) DEFAULT 'COLD' CHECK (lead_temperature IN ('HOT', 'WARM', 'COLD')),
  status VARCHAR(50) DEFAULT 'NEW' CHECK (status IN ('NEW', 'CONTACTED', 'QUALIFIED', 'INTERESTED', 'READY_TO_REGISTER', 'REGISTERED', 'CUSTOMER', 'LOST')),
  assigned_agent_id VARCHAR(36) REFERENCES users(id) ON DELETE SET NULL,
  last_contact_at TIMESTAMP WITH TIME ZONE,
  next_follow_up_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS conversations (
  id VARCHAR(36) PRIMARY KEY,
  customer_id VARCHAR(36) NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  state VARCHAR(50) DEFAULT 'AI_ACTIVE' CHECK (state IN ('AI_ACTIVE', 'WAITING_FOR_CUSTOMER', 'HUMAN_REQUIRED', 'HUMAN_ACTIVE', 'RESOLVED', 'ARCHIVED')),
  summary TEXT,
  assigned_agent_id VARCHAR(36) REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS messages (
  id VARCHAR(36) PRIMARY KEY,
  conversation_id VARCHAR(36) NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  external_message_id VARCHAR(255) UNIQUE,
  direction VARCHAR(20) NOT NULL CHECK (direction IN ('INBOUND', 'OUTBOUND')),
  sender_type VARCHAR(20) NOT NULL CHECK (sender_type IN ('CUSTOMER', 'AI', 'AGENT', 'SYSTEM')),
  sender_id VARCHAR(36),
  content TEXT NOT NULL,
  message_type VARCHAR(50) DEFAULT 'text',
  status VARCHAR(50) DEFAULT 'sent',
  intent VARCHAR(100),
  metadata JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS knowledge_items (
  id VARCHAR(36) PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  category VARCHAR(100) NOT NULL,
  content TEXT NOT NULL,
  is_published BOOLEAN DEFAULT TRUE,
  priority INTEGER DEFAULT 0,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

